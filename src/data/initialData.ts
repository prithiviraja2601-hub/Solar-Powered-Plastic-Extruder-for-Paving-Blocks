export function calculateBinStatus(currentWeight: number, maxCapacity: number): BinStatus {
  const fillPct = (currentWeight / maxCapacity) * 100;
  if (fillPct > 90) return 'COLLECTION_REQUIRED';
  if (fillPct >= 90) return 'FULL';
  if (fillPct >= 70) return 'NEARLY_FULL';
  return 'AVAILABLE';
}

